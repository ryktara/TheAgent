def _thresholds() -> dict:
    return F.parse_yaml(THRESHOLDS.read_text(encoding="utf-8")) if THRESHOLDS.exists() else {}


def _norm(text: str) -> list[str]:
    out = []
    for line in text.splitlines():
        if any(rx.search(line) for rx in GOLDEN_ALLOW):
            out.append("<allowlisted>")
        else:
            out.append(line.rstrip())
    return out


def _regen_all(tmp: Path, root: Path = ROOT) -> None:
    import foundry_security as X
    _run_to_screens(tmp, ROOT); X.run_threat_skeleton(tmp, ROOT); X.run_tickets_skeleton(tmp, ROOT)


def _golden_one(slug: str, update: bool) -> list[str]:
    golden = EXPECTED / slug
    tmp = _fixture_copy(slug)
    try:
        t0 = time.time(); _regen_all(tmp); secs = time.time() - t0
        files = sorted(p for p in tmp.rglob("*") if p.is_file() and p.suffix in (".md", ".yaml", ".prisma") and ".pg" not in p.parts)
        if update:
            if golden.exists():
                shutil.rmtree(golden)
            for f in files:
                dst = golden / f.relative_to(tmp); dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy(f, dst)
            print(f"golden {slug}: wrote {len(files)} files to {golden.relative_to(ROOT)}")
            return []
        if not golden.exists():
            return [f"no expected artefacts for {slug}; run `python evals/run.py --stage golden --update-golden`"]
        expected = {p.relative_to(golden).as_posix(): p for p in golden.rglob("*") if p.is_file()}
        got = {p.relative_to(tmp).as_posix(): p for p in files}
        errs = []
        for rel in sorted(set(expected) | set(got)):
            if rel not in got:
                errs.append(f"missing: {rel}"); continue
            if rel not in expected:
                errs.append(f"unexpected new artefact: {rel}"); continue
            a, b = _norm(expected[rel].read_text(encoding="utf-8")), _norm(got[rel].read_text(encoding="utf-8"))
            if a != b:
                first = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
                errs.append(f"changed: {rel} (first diff at line {first + 1}: {a[first][:60] if first < len(a) else '<eof>'!r} → {b[first][:60] if first < len(b) else '<eof>'!r})")
        th = (_thresholds().get("skeleton_wall_s") or {})
        budget = sum(float(v) for v in th.values()) if th else None
        if budget and secs > budget:
            errs.append(f"skeleton wall {secs:.0f}s exceeds thresholds.yaml budget {budget:.0f}s")
        print(f"golden {slug}: {len(got)} artefacts compared in {secs:.0f}s; {'pass' if not errs else str(len(errs)) + ' differences'}")
        return errs
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def stage_golden(cases, update: bool = False) -> int:
    """C3: regenerate every phase 4–10 artefact per fixture and diff against evals/expected/<slug>."""
    slugs = fixture_slugs(); passed = 0
    for slug in slugs:
        errs = _golden_one(slug, update)
        for e in errs:
            print("    " + e)
        passed += not errs
    print(f"\ngolden: {passed}/{len(slugs)} pass")
    return 0 if slugs and passed == len(slugs) else 1


def _latest(prefix: str) -> Path | None:
    files = sorted(RESULTS.glob(f"{prefix}-*.json")) if RESULTS.exists() else []
    return files[-1] if files else None


def stage_results(cases) -> int:
    """Read the newest evals/results/{triggers,e2e}-<date>.json (written by /foundry-eval in a Claude Code session)."""
    th = _thresholds().get("e2e") or {}
    rc = 0
    tp = _latest("triggers")
    if tp:
        d = json.loads(tp.read_text(encoding="utf-8"))
        need = float(th.get("trigger_accuracy_min", 0.9))
        ok = float(d.get("accuracy", 0)) >= need
        rc |= not ok
        print(f"results triggers {tp.name}: {d.get('correct')}/{d.get('total')} = {float(d.get('accuracy', 0)):.0%} ({'pass' if ok else 'FAIL'}, threshold {need:.0%}, model {d.get('model')})")
    else:
        print("results triggers: none yet — run /foundry-eval --stage triggers in Claude Code")
    ep = _latest("e2e")
    if ep:
        d = json.loads(ep.read_text(encoding="utf-8"))
        ok = not d.get("errors")
        rc |= not ok
        print(f"results e2e {ep.name}: {'pass' if ok else 'FAIL'} ({d.get('pack')}, {d.get('tickets')} tickets, {d.get('asked')} questions, build {d.get('build_wall_s')}s)")
        for e in d.get("errors") or []:
            print("    " + e)
    else:
        print("results e2e: none yet — run /foundry-eval --stage e2e in Claude Code")
    print(f"\nresults: {'pass' if not rc else 'FAIL'}")
    return int(rc)


def score_triggers(answers_path: Path, model: str | None) -> int:
    """/foundry-eval --stage triggers: the session answers every prompt in evals/triggers.csv; this scores and records it."""
    rows = list(csv.DictReader((ROOT / "evals" / "triggers.csv").open(encoding="utf-8", newline="")))
    answers = json.loads(answers_path.read_text(encoding="utf-8"))
    wrong = []; ok = 0
    for r in rows:
        ans = str(answers.get(r["prompt"], "")).strip().strip("`/").lower()
        hit = ans == r["expected"].lower()
        ok += hit
        if not hit:
            wrong.append({"prompt": r["prompt"], "expected": r["expected"], "got": ans or "<missing>"})
    acc = ok / len(rows) if rows else 0.0
    need = float((_thresholds().get("e2e") or {}).get("trigger_accuracy_min", 0.9))
    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / f"triggers-{F._now()[:10]}.json"
    out.write_text(json.dumps({"date": F._now(), "model": model or "session", "total": len(rows), "correct": ok, "accuracy": round(acc, 4), "threshold": need, "wrong": wrong}, indent=1), encoding="utf-8", newline="\n")
    for w in wrong:
        print(f"    {w['prompt'][:50]!r}: expected {w['expected']}, got {w['got']}")
    print(f"\ntriggers: {ok}/{len(rows)} = {acc:.0%} ({'pass' if acc >= need else 'FAIL'}, threshold {need:.0%}) → {out.relative_to(ROOT).as_posix()}")
    return 0 if acc >= need else 1


def assert_e2e(project: Path, phases_wall: float | None, build_wall: float | None, pack: str | None) -> int:
    """/foundry-eval --stage e2e: after the session ran /foundry --unattended and /foundry-build --n 2 in `project`,
    check gates 0–10, question count, ticket count, DoD for T-000/T-001, per-ticket ceilings; record the result."""
    th = _thresholds().get("e2e") or {}
    errs: list[str] = []
    dec = project / ".foundry" / "decisions.yaml"
    asked = len(re.findall(r"source: \"(?:human|user)\"", dec.read_text(encoding="utf-8"))) if dec.exists() else 0
    for g in range(11):
        r = subprocess.run([sys.executable, str(ROOT / "scripts" / "foundry.py"), "gate", str(g), "--dir", str(project)], capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode != 0:
            errs.append(f"gate {g} failed: {r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr[-200:]}")
    n_tickets = len(list((project / ".foundry" / "tickets").glob("T-???-*.md"))) if (project / ".foundry" / "tickets").exists() else 0
    if asked > int(th.get("questions_asked_max", 0)):
        errs.append(f"questions asked {asked} > {th.get('questions_asked_max')}")
    if not (int(th.get("tickets_min", 35)) <= n_tickets <= int(th.get("tickets_max", 60))):
        errs.append(f"ticket count {n_tickets} outside {th.get('tickets_min')}–{th.get('tickets_max')}")
    if phases_wall is not None and phases_wall > float(th.get("phases_wall_s_max", 2400)):
        errs.append(f"phases wall {phases_wall:.0f}s > {th.get('phases_wall_s_max')}")
    if build_wall is not None and build_wall > float(th.get("build_wall_s_max", 2400)):
        errs.append(f"build wall {build_wall:.0f}s > {th.get('build_wall_s_max')}")
    for tid in ("T-000", "T-001"):
        st = project / ".foundry" / "tickets" / f"{tid}.status.yaml"
        if not st.exists() or not F.parse_yaml(st.read_text(encoding="utf-8")).get("last", {}).get("passed"):
            errs.append(f"{tid} DoD not green")
    per: dict = {}
    if (project / ".foundry" / "metrics.jsonl").exists():
        import foundry_ops as O
        per = O._aggregate(project / ".foundry" / "metrics.jsonl")
    for tid, d in per.items():
        if tid == "T-000" or not d.get("cost_usd"):
            continue
        if d["cost_usd"] > float(th.get("per_ticket_cost_usd_max", 20)):
            errs.append(f"{tid} cost ${d['cost_usd']:.2f} > {th.get('per_ticket_cost_usd_max')}")
        if d["t_out"] > int(th.get("per_ticket_output_tokens_max", 40000)):
            errs.append(f"{tid} output {d['t_out']} > {th.get('per_ticket_output_tokens_max')}")
        if d["t_cache_read"] > int(th.get("per_ticket_cache_read_max", 8000000)):
            errs.append(f"{tid} cache_read {d['t_cache_read']} > {th.get('per_ticket_cache_read_max')}")
    RESULTS.mkdir(parents=True, exist_ok=True)
    out = RESULTS / f"e2e-{F._now()[:10]}.json"
    out.write_text(json.dumps({"date": F._now(), "project": project.name,  # folder name only: no machine paths in tracked results "pack": pack, "asked": asked, "tickets": n_tickets, "phases_wall_s": phases_wall, "build_wall_s": build_wall,
                               "per_ticket": {k: {"cost_usd": round(v.get("cost_usd", 0), 2), "t_out": v.get("t_out"), "t_cache_read": v.get("t_cache_read")} for k, v in per.items()}, "errors": errs}, indent=1), encoding="utf-8", newline="\n")
    for e in errs:
        print("    " + e)
    print(f"\ne2e: {'1/1' if not errs else '0/1'} pass → {out.relative_to(ROOT).as_posix()}")
    return 0 if not errs else 1


def update_thresholds(project: Path | None) -> int:
    """Rewrite thresholds.yaml from the latest measurements (+25%): skeleton walls from a golden run, per-ticket ceilings from a project's metrics."""
    th = _thresholds()
    tmp = _fixture_copy()
    try:
        import foundry_phases as P, foundry_design as D, foundry_security as X
        walls = {}
        for name, fn in (("domain", lambda: P.run_domain_skeleton(tmp, ROOT)), ("architecture", lambda: P.run_arch_skeleton(tmp, ROOT)), ("data", lambda: P.run_schema_skeleton(tmp, ROOT, "prisma")), ("api", lambda: P.run_api_skeleton(tmp, ROOT)),
                         ("design", lambda: D.run_design_skeleton(tmp, ROOT)), ("screens", lambda: D.run_screens_skeleton(tmp, ROOT)), ("security", lambda: X.run_threat_skeleton(tmp, ROOT)), ("tickets", lambda: X.run_tickets_skeleton(tmp, ROOT))):
            t0 = time.time(); fn(); walls[name] = max(10, round((time.time() - t0) * 1.25 + 1))  # floor 10 s: CI machines are slower than the dev box
        th["skeleton_wall_s"] = walls
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if project and (project / ".foundry" / "metrics.jsonl").exists():
        import foundry_ops as O
        per = {k: v for k, v in O._aggregate(project / ".foundry" / "metrics.jsonl").items() if v["cost_usd"] > 0}
        if per:
            best = lambda key: sorted(v[key] for v in per.values())[len(per) // 2]  # median
            e2e = th.setdefault("e2e", {})
            e2e["per_ticket_cost_usd_max"] = round(best("cost_usd") * 1.25, 2)
            e2e["per_ticket_output_tokens_max"] = int(best("t_out") * 1.25)
            e2e["per_ticket_cache_read_max"] = int(best("t_cache_read") * 1.25)
    th["as_of"] = F._now()[:10]
    THRESHOLDS.write_text(F.dump_yaml(th), encoding="utf-8", newline="\n")
    print(f"thresholds: updated {THRESHOLDS.relative_to(ROOT)}: {json.dumps(th)[:400]}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=STAGES, help="run one stage (default: every deterministic stage)")
    ap.add_argument("--score-triggers", type=Path, help="answers.json from /foundry-eval → evals/results/triggers-<date>.json")
    ap.add_argument("--assert-e2e", type=Path, help="project dir run by /foundry-eval --stage e2e → evals/results/e2e-<date>.json")
    ap.add_argument("--phases-wall", type=float); ap.add_argument("--build-wall", type=float); ap.add_argument("--pack"); ap.add_argument("--model")
    ap.add_argument("--update-golden", action="store_true", help="rewrite evals/expected/restaurant-pos from the fixture")
    ap.add_argument("--update-thresholds", action="store_true", help="rewrite evals/thresholds.yaml (+25%%) from measurements; --project adds per-ticket ceilings")
    ap.add_argument("--project", type=Path, help="project dir with .foundry/metrics.jsonl for --update-thresholds")
    a = ap.parse_args(argv)
    if a.score_triggers:
        return score_triggers(a.score_triggers, a.model)
    if a.assert_e2e:
        return assert_e2e(a.assert_e2e.resolve(), a.phases_wall, a.build_wall, a.pack)
    if a.update_thresholds:
        return update_thresholds(a.project)
    if a.update_golden:
        return stage_golden([], update=True)
    cases = load_cases()
    if not cases:
        print("no briefs found")
        return 1
    rc = 0
    default = list(STAGES)
    for st in ([a.stage] if a.stage else default):
        fn = {"match": stage_match, "grill": stage_grill, "prd": stage_prd, "domain": stage_domain,
              "architecture": stage_architecture, "data": stage_data, "api": stage_api, "design": stage_design, "screens": stage_screens, "security": stage_security, "tickets": stage_tickets,
              "golden": stage_golden, "results": stage_results}[st]
        rc |= fn(load_cases(include_variants=True) if st == "match" else cases)
        print()
    if not a.stage:
        print("model stages: run /foundry-eval in Claude Code (--stage triggers | --stage e2e); results land in evals/results/")
    return rc


