def _thresholds() -> dict:
    return F.parse_yaml(THRESHOLDS.read_text(encoding="utf-8")) if THRESHOLDS.exists() else {}


def _norm(text: str) -> list[str]:
    out = []
    for line in text.splitlines():
        if any(rx.search(line) for rx in GOLDEN_ALLOW):
            out.append("<allowlisted>")
        else:
            out.append(line.rstrip())
    return out


def _regen_all(tmp: Path) -> None:
    import foundry_security as X
    _run_to_screens(tmp, ROOT); X.run_threat_skeleton(tmp, ROOT); X.run_tickets_skeleton(tmp, ROOT)


def stage_golden(cases, update: bool = False) -> int:
    """C3: regenerate every phase 4–10 artefact from the fixture and diff against evals/expected/restaurant-pos."""
    tmp = _fixture_copy()
    try:
        t0 = time.time(); _regen_all(tmp); secs = time.time() - t0
        files = sorted(p for p in tmp.rglob("*") if p.is_file() and p.suffix in (".md", ".yaml", ".prisma") and ".pg" not in p.parts)
        if update:
            if GOLDEN.exists():
                shutil.rmtree(GOLDEN)
            for f in files:
                dst = GOLDEN / f.relative_to(tmp); dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy(f, dst)
            print(f"golden: wrote {len(files)} files to {GOLDEN.relative_to(ROOT)}")
            return 0
        if not GOLDEN.exists():
            print("golden: no expected artefacts; run `python evals/run.py --stage golden --update-golden`"); return 1
        expected = {p.relative_to(GOLDEN).as_posix(): p for p in GOLDEN.rglob("*") if p.is_file()}
        got = {p.relative_to(tmp).as_posix(): p for p in files}
        errs = []
        for rel in sorted(set(expected) | set(got)):
            if rel not in got:
                errs.append(f"missing: {rel}"); continue
            if rel not in expected:
                errs.append(f"unexpected new artefact: {rel}"); continue
            a, b = _norm(expected[rel].read_text(encoding="utf-8")), _norm(got[rel].read_text(encoding="utf-8"))
            if a != b:
                first = next((i for i, (x, y) in enumerate(zip(a, b)) if x != y), min(len(a), len(b)))
                errs.append(f"changed: {rel} (first diff at line {first + 1}: {a[first][:60] if first < len(a) else '<eof>'!r} → {b[first][:60] if first < len(b) else '<eof>'!r})")
        th = (_thresholds().get("skeleton_wall_s") or {})
        budget = sum(float(v) for v in th.values()) if th else None
        if budget and secs > budget:
            errs.append(f"skeleton wall {secs:.0f}s exceeds thresholds.yaml budget {budget:.0f}s")
        for e in errs:
            print("    " + e)
        print(f"golden: {len(got)} artefacts compared in {secs:.0f}s; {'pass' if not errs else str(len(errs)) + ' differences'}")
        print(f"\ngolden: {'1/1' if not errs else '0/1'} pass")
        return 0 if not errs else 1
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _claude_available() -> str | None:
    exe = shutil.which("claude")
    if not exe:
        return "claude CLI not on PATH"
    # A real probe: `claude auth status` reports ok even when -p cannot run non-interactively; ask for one token instead.
    try:
        code, out = _claude_p("Reply with the single word ok.", ROOT, 120, "haiku")
    except subprocess.TimeoutExpired:
        return "claude -p probe timed out"
    low = out.lower()
    if "not logged in" in low or "please run /login" in low or "api key" in low and "invalid" in low:
        return "claude CLI is not logged in for non-interactive use (run `claude /login` or set ANTHROPIC_API_KEY)"
    if code != 0 and "ok" not in low:
        return f"claude -p probe failed (exit {code}): {out.strip()[:120]}"
    return None


def _claude_p(prompt: str, cwd: Path, timeout: int, model: str = "sonnet") -> tuple[int, str]:
    exe = shutil.which("claude") or "claude"
    cmd = [exe, "-p", prompt, "--model", model, "--dangerously-skip-permissions", "--output-format", "text"]
    r = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout, encoding="utf-8", errors="replace", shell=(os.name == "nt"))
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def stage_triggers(cases) -> int:
    """C4: 40 prompts → expected skill (or none), judged by `claude -p` with the plugin loaded; ≥ trigger_accuracy_min."""
    why = _claude_available()
    if why:
        print(f"triggers: skipped ({why})"); return 0
    rows = list(csv.DictReader((ROOT / "evals" / "triggers.csv").open(encoding="utf-8", newline="")))
    names = sorted(p.parent.name for p in (ROOT / "skills").glob("*/SKILL.md"))
    ok = 0; wrong = []
    for r in rows:
        q = ("You have the Foundry plugin skills loaded: " + ", ".join(names) + ". For the user message below, answer with the single skill name you would invoke, "
             "or the word none if no skill applies. Answer with the name only.\n\nUser message: " + r["prompt"])
        code, out = _claude_p(q, ROOT, 120, "haiku")
        ans = (out.strip().splitlines() or [""])[-1].strip().strip("`/").lower()
        hit = ans == r["expected"].lower()
        ok += hit
        if not hit:
            wrong.append(f"    {r['prompt'][:50]!r}: expected {r['expected']}, got {ans or '<empty>'}")
    acc = ok / len(rows) if rows else 0
    for w in wrong:
        print(w)
    need = float((_thresholds().get("e2e") or {}).get("trigger_accuracy_min", 0.9))
    print(f"\ntriggers: {ok}/{len(rows)} = {acc:.0%} ({'pass' if acc >= need else 'FAIL'}, threshold {need:.0%})")
    return 0 if acc >= need else 1


def stage_e2e(cases) -> int:
    """C1: unattended phases 0–10 on the Sharjah brief, then /foundry-build --n 2, then gate release, all through `claude -p`."""
    why = _claude_available()
    if why:
        print(f"e2e: skipped ({why})"); return 0
    th = _thresholds().get("e2e") or {}
    brief = (BRIEFS / "restaurant-pos.md").read_text(encoding="utf-8")
    tmp = Path(tempfile.mkdtemp(prefix="foundry-e2e-"))
    subprocess.run(["git", "init", "-q"], cwd=str(tmp))
    errs = []
    try:
        t0 = time.time()
        code, out = _claude_p(f"/foundry --unattended {brief.strip()}", tmp, int(th.get("phases_wall_s_max", 2400)) + 600, "sonnet")
        phases_s = time.time() - t0
        asked = len(re.findall(r"source: \"(?:human|user)\"", (tmp / ".foundry" / "decisions.yaml").read_text(encoding="utf-8"))) if (tmp / ".foundry" / "decisions.yaml").exists() else 0
        for g in range(11):
            r = subprocess.run([sys.executable, str(ROOT / "scripts" / "foundry.py"), "gate", str(g), "--dir", str(tmp)], capture_output=True, text=True, encoding="utf-8", errors="replace")
            if r.returncode != 0:
                errs.append(f"gate {g} failed: {r.stdout.strip().splitlines()[-1] if r.stdout.strip() else r.stderr[-200:]}")
        n_tickets = len(list((tmp / ".foundry" / "tickets").glob("T-*.md")))
        if asked > int(th.get("questions_asked_max", 0)):
            errs.append(f"questions asked {asked} > {th.get('questions_asked_max')}")
        if not (int(th.get("tickets_min", 35)) <= n_tickets <= int(th.get("tickets_max", 60))):
            errs.append(f"ticket count {n_tickets} outside {th.get('tickets_min')}–{th.get('tickets_max')}")
        if phases_s > float(th.get("phases_wall_s_max", 2400)):
            errs.append(f"phases wall {phases_s:.0f}s > {th.get('phases_wall_s_max')}")
        if not errs:
            t1 = time.time()
            code, out = _claude_p("/foundry-build --n 2", tmp, int(th.get("build_wall_s_max", 2400)) + 600, "sonnet")
            build_s = time.time() - t1
            subprocess.run([sys.executable, str(ROOT / "scripts" / "foundry.py"), "metrics", "ingest", "--dir", str(tmp)], capture_output=True, text=True)
            import foundry_ops as O
            per = O._aggregate(tmp / ".foundry" / "metrics.jsonl") if (tmp / ".foundry" / "metrics.jsonl").exists() else {}
            for tid in ("T-000", "T-001"):
                st = tmp / ".foundry" / "tickets" / f"{tid}.status.yaml"
                if not st.exists() or not F.parse_yaml(st.read_text(encoding="utf-8")).get("last", {}).get("passed"):
                    errs.append(f"{tid} DoD not green")
            for tid, d in per.items():
                if tid == "T-000":
                    continue
                if d["cost_usd"] > float(th.get("per_ticket_cost_usd_max", 20)):
                    errs.append(f"{tid} cost ${d['cost_usd']:.2f} > {th.get('per_ticket_cost_usd_max')}")
                if d["t_out"] > int(th.get("per_ticket_output_tokens_max", 40000)):
                    errs.append(f"{tid} output {d['t_out']} > {th.get('per_ticket_output_tokens_max')}")
                if d["t_cache_read"] > int(th.get("per_ticket_cache_read_max", 8000000)):
                    errs.append(f"{tid} cache_read {d['t_cache_read']} > {th.get('per_ticket_cache_read_max')}")
            if build_s > float(th.get("build_wall_s_max", 2400)):
                errs.append(f"build wall {build_s:.0f}s > {th.get('build_wall_s_max')}")
            r = subprocess.run([sys.executable, str(ROOT / "scripts" / "foundry.py"), "release-skeleton", "--dir", str(tmp)], capture_output=True, text=True)
            r = subprocess.run([sys.executable, str(ROOT / "scripts" / "foundry.py"), "gate", "release", "--dir", str(tmp)], capture_output=True, text=True, encoding="utf-8", errors="replace")
            if r.returncode != 0:
                errs.append("gate release failed: " + (r.stdout.strip().splitlines()[-1] if r.stdout.strip() else ""))
        for e in errs:
            print("    " + e)
        print(f"\ne2e: {'1/1' if not errs else '0/1'} pass (dir kept at {tmp})")
        return 0 if not errs else 1
    except subprocess.TimeoutExpired as e:
        print(f"e2e: timeout after {e.timeout}s (dir kept at {tmp})"); return 1


def update_thresholds(project: Path | None) -> int:
    """Rewrite thresholds.yaml from the latest measurements (+25%): skeleton walls from a golden run, per-ticket ceilings from a project's metrics."""
    th = _thresholds()
    tmp = _fixture_copy()
    try:
        import foundry_phases as P, foundry_design as D, foundry_security as X
        walls = {}
        for name, fn in (("domain", lambda: P.run_domain_skeleton(tmp, ROOT)), ("architecture", lambda: P.run_arch_skeleton(tmp, ROOT)), ("data", lambda: P.run_schema_skeleton(tmp, ROOT, "prisma")), ("api", lambda: P.run_api_skeleton(tmp, ROOT)),
                         ("design", lambda: D.run_design_skeleton(tmp, ROOT)), ("screens", lambda: D.run_screens_skeleton(tmp, ROOT)), ("security", lambda: X.run_threat_skeleton(tmp, ROOT)), ("tickets", lambda: X.run_tickets_skeleton(tmp, ROOT))):
            t0 = time.time(); fn(); walls[name] = max(2, round((time.time() - t0) * 1.25 + 1))
        th["skeleton_wall_s"] = walls
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    if project and (project / ".foundry" / "metrics.jsonl").exists():
        import foundry_ops as O
        per = {k: v for k, v in O._aggregate(project / ".foundry" / "metrics.jsonl").items() if v["cost_usd"] > 0}
        if per:
            best = lambda key: sorted(v[key] for v in per.values())[len(per) // 2]  # median
            e2e = th.setdefault("e2e", {})
            e2e["per_ticket_cost_usd_max"] = round(best("cost_usd") * 1.25, 2)
            e2e["per_ticket_output_tokens_max"] = int(best("t_out") * 1.25)
            e2e["per_ticket_cache_read_max"] = int(best("t_cache_read") * 1.25)
    th["as_of"] = F._now()[:10]
    THRESHOLDS.write_text(F.dump_yaml(th), encoding="utf-8", newline="\n")
    print(f"thresholds: updated {THRESHOLDS.relative_to(ROOT)}: {json.dumps(th)[:400]}")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", choices=STAGES, help="run one stage (default: every stage without a model; e2e/triggers only when asked)")
    ap.add_argument("--update-golden", action="store_true", help="rewrite evals/expected/restaurant-pos from the fixture")
    ap.add_argument("--update-thresholds", action="store_true", help="rewrite evals/thresholds.yaml (+25%%) from measurements; --project adds per-ticket ceilings")
    ap.add_argument("--project", type=Path, help="project dir with .foundry/metrics.jsonl for --update-thresholds")
    a = ap.parse_args(argv)
    if a.update_thresholds:
        return update_thresholds(a.project)
    if a.update_golden:
        return stage_golden([], update=True)
    cases = load_cases()
    if not cases:
        print("no briefs found")
        return 1
    rc = 0
    default = [s for s in STAGES if s not in ("e2e", "triggers")]
    for st in ([a.stage] if a.stage else default):
        fn = {"match": stage_match, "grill": stage_grill, "prd": stage_prd, "domain": stage_domain,
              "architecture": stage_architecture, "data": stage_data, "api": stage_api, "design": stage_design, "screens": stage_screens, "security": stage_security, "tickets": stage_tickets,
              "golden": stage_golden, "triggers": stage_triggers, "e2e": stage_e2e}[st]
        rc |= fn(load_cases(include_variants=True) if st == "match" else cases)
        print()
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
