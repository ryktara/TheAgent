"""Foundry eval runner.

Stages:
  match   run foundry.py match on every golden brief; compare to expected_pack / min_confidence.
  grill   match -> apply-prefilled -> grill-plan round 1 in a temp dir; check budget and confirms.
  prd     gate prd against the fixture under evals/fixtures/restaurant-pos.
  domain, architecture, data, api, design, screens, security, tickets   run the phase skeletons on the fixture and their gates.
  golden    regenerate phase 4–10 artefacts and diff against evals/expected/restaurant-pos (allowlist for dates/hashes).
  triggers  40 prompts → skill via `claude -p` (needs the CLI logged in); ≥ thresholds.e2e.trigger_accuracy_min.
  e2e       unattended phases 0–10 + /foundry-build --n 2 + gate release via `claude -p`; ceilings from thresholds.yaml.

Usage: python evals/run.py [--stage <name>] [--update-golden] [--update-thresholds [--project <dir>]]
"""
